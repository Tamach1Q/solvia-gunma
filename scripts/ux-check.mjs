import { chromium } from 'playwright'
import { mkdir, writeFile } from 'node:fs/promises'
const baseUrl = process.argv[2] || 'http://localhost:8888'
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH } : {}) })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const checks = [], errors = []
page.on('pageerror', error => errors.push(error.message))
const assert = (ok, label) => { if (!ok) throw new Error(label); checks.push(label) }
const nav = async id => { const button = page.getByTestId(`nav-${id}`); if (!(await button.isVisible())) await page.getByTestId('mobile-menu').click(); await button.click() }
const fits = async label => assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), label)
await mkdir('artifacts', { recursive: true })
try {
  await page.goto(baseUrl)
  await page.getByTestId('login-email').fill('admin@backup-system.demo')
  await page.getByTestId('login-password').fill('gunma1125')
  await page.getByTestId('login-submit').click()
  await page.getByTestId('monitoring-screen').waitFor()
  assert(true, '初回の入口は統合監視')
  const monitoredSite = page.getByTestId('monitoring-row').filter({ hasText: '渋川市 第2太陽光発電所' })
  await monitoredSite.getByRole('button', { name: '渋川市 第2太陽光発電所の操作', exact: true }).click()
  await monitoredSite.getByRole('button', { name: '点検・報告書を開く' }).click()
  await page.getByTestId('request-field').click()
  const modal = page.getByTestId('assignment-modal')
  await modal.getByRole('link', { name: '現場画面を開く' }).waitFor()
  await modal.getByText('その他の操作', { exact: true }).click()
  await modal.getByText('現場画面が「保存済み」になってから', { exact: false }).waitFor()
  await modal.getByTestId('open-local-field-here').click()
  const field = page.getByTestId('local-field')
  await field.getByRole('button', { name: '晴れ', exact: true }).click()
  await field.getByTestId('start-inspection').click()
  assert(await field.locator('[data-testid^="visual-"]').count() === 6, '現場入力は現在の1区分だけ表示')
  assert(await field.locator('textarea').count() === 0, '正常・未判定項目の任意欄は閉じている')
  const height = await field.getByTestId('field-visual').evaluate(x => x.getBoundingClientRect().height)
  assert(height < 2400, `最初の区分の長さを短縮（${Math.round(height)}px）`)
  await field.getByTestId('next-category').click()
  assert(await field.locator('[data-testid^="visual-"]').count() === 3, '次の区分へ移動できる')
  await field.getByRole('combobox', { name: '点検区分' }).selectOption('0')
  await field.getByTestId('visual-1-1').getByRole('radio', { name: '△', exact: true }).click()
  await field.getByTestId('visual-1-1').getByText('写真（必須）：指摘の状態が分かる写真を追加してください', { exact: true }).waitFor()
  await field.getByTestId('step-check').click()
  await field.getByRole('button', { name: '発電所全景 △なのに写真がありません' }).click()
  assert(await field.getByRole('combobox', { name: '点検区分' }).inputValue() === '0', '不足項目から正しい区分・入力欄に戻れる')
  await field.getByTestId('visual-1-1').getByRole('radio', { name: '○', exact: true }).click()
  await field.getByTestId('step-check').click()
  await field.getByTestId('fill-rest').click()
  await field.getByTestId('submit-inspection').waitFor()
  await field.getByText('要観察（△）', { exact: true }).waitFor()
  assert(await field.locator('.field-review-items li').count() === 5, '提出前に要観察4件と要対応1件を見直せる')
  await page.setViewportSize({ width: 390, height: 844 })
  await fits('390px：現場入力のはみ出しなし')
  await page.screenshot({ path: 'artifacts/ux-field-check-mobile.png' })
  await field.getByTestId('submit-inspection').click()
  await field.getByTestId('make-report-from-local').click()
  await page.getByTestId('report-document').waitFor()
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 900 })
    await page.evaluate(() => scrollTo(0, 0))
    await fits(`${width}px：報告書のはみ出しなし`)
    const position = await page.getByTestId('edit-report').boundingBox()
    assert(position.y < 700, `${width}px：編集操作を上部に表示（${Math.round(position.y)}px）`)
    assert(!(await page.locator('.report-rating').count()), '作成中は評価フォームを表示しない')
    await page.screenshot({ path: `artifacts/ux-report-${width}.png` })
  }
  await page.getByTestId('edit-report').click()
  assert(await page.getByTestId('report-editor').locator('input').first().evaluate(x => document.activeElement === x), '編集開始時に入力欄へフォーカス')
  const editorTop = await page.getByTestId('report-editor').boundingBox()
  assert(editorTop.y >= 0 && editorTop.y < 150, '編集欄が画面内に移動する')
  await page.getByTestId('edit-report').click()
  const reportHash = new URL(page.url()).hash
  await page.reload()
  await page.getByTestId('report-document').waitFor()
  assert(new URL(page.url()).hash === reportHash, '再読込しても同じ報告書を復元')
  await nav('monitoring')
  await page.goBack()
  await page.getByTestId('report-document').waitFor()
  await page.goForward()
  await page.getByTestId('monitoring-screen').waitFor()
  assert(true, 'ブラウザの戻る・進むで画面を復元')
  await page.getByRole('button', { name: '報告書一覧', exact: true }).click()
  await page.getByRole('button', { name: '完成済みの報告書を見る' }).click()
  await page.getByRole('button', { name: '渋川市 第5太陽光発電所の報告書を表示', exact: true }).click()
  await page.getByTestId('report-document').waitFor()
  assert(true, '完成済みの報告書を一覧から直接表示')
  await fits('390px：完成済み報告書のはみ出しなし')
  await page.screenshot({ path: 'artifacts/ux-report-B-mobile.png' })
  await nav('repairs')
  await fits('390px：修繕一覧のはみ出しなし')
  const first = page.getByTestId('repair-row').first().getByRole('button')
  assert((await first.boundingBox()).width > 100, '修繕の案件名をカード表示で読める幅にする')
  await page.screenshot({ path: 'artifacts/ux-repairs-mobile.png' })
  assert(errors.length === 0, `コンソールエラーなし：${errors.join(',')}`)
  await writeFile('artifacts/ux-check.json', JSON.stringify({ checks, fieldSectionHeight: Math.round(height) }, null, 2))
  console.log(`UX check passed（${checks.length}件）`)
} finally { await browser.close() }
